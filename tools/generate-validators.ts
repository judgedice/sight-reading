/**
 * Generates `src/store/export-file-validator.js`: the backup-file validator, precompiled by Ajv's standalone code
 * generator from `schemas/export-file.schema.json`. The app imports this module instead of the Ajv runtime, which
 * cost about 40 KB gzip of the bundle budget (PLAN ruling 39). The code is what `new Ajv(AJV_OPTIONS).compile(schema)`
 * builds at run time, so validation and error objects are unchanged.
 *
 *   pnpm validators          write the file
 *   pnpm validators --check  exit 1 if the committed file differs (run after `pnpm schemas`)
 *
 * tools/generate-validators.test.ts runs the check in `pnpm test`.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SCHEMA_FILE = join(root, 'schemas/export-file.schema.json');
export const VALIDATOR_FILE = join(root, 'src/store/export-file-validator.js');

/** The options export-import.ts used with the Ajv runtime. */
export const AJV_OPTIONS = { strict: false, allErrors: false } as const;

const HEADER =
  '// Generated by tools/generate-validators.ts from schemas/export-file.schema.json. Do not edit; run `pnpm validators`.\n' +
  '/* eslint-disable */\n';

/** The validator module source. Pure apart from reading the schema. */
export function generateValidator(): string {
  const schema = JSON.parse(readFileSync(SCHEMA_FILE, 'utf8')) as object;
  const ajv = new Ajv({ ...AJV_OPTIONS, code: { source: true, esm: true } });
  const code = standaloneCode(ajv, ajv.compile(schema));
  return `${HEADER}${code}\n`;
}

/** Problems with the committed file; empty when it matches. */
export function checkValidator(generated: string): string[] {
  if (!existsSync(VALIDATOR_FILE)) return ['missing: src/store/export-file-validator.js'];
  if (readFileSync(VALIDATOR_FILE, 'utf8') !== generated) {
    return ['drift: src/store/export-file-validator.js differs from schemas/export-file.schema.json'];
  }
  return [];
}

function main(argv: string[]): void {
  const generated = generateValidator();
  if (argv.includes('--check')) {
    const problems = checkValidator(generated);
    if (problems.length > 0) {
      console.error(problems.join('\n'));
      console.error('Run `pnpm validators` and commit the result.');
      process.exit(1);
    }
    return;
  }
  writeFileSync(VALIDATOR_FILE, generated);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
