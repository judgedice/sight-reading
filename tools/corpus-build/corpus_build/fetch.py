"""C1: fetch the pinned sources into the clone cache, lock them, and verify the lock (03 section 3.3).

Clones are blobless and sparse (full checkouts are 842 MB and 2.4 GB). The cache lives outside the repo.
The lock records the pinned SHA, the SHA-256 of every file used and the SHA-256 of each upstream licence file.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import subprocess
from pathlib import Path
from typing import Any

from .candidate import make_record
from .paths import LOCK_YAML
from .sources import Source
from .yamlio import dump_yaml, load_yaml

LOCK_VERSION = 1
LOCK_HEADER = (
    "Generated by `python -m corpus_build lock`. Do not edit.\n"
    "Pins each upstream commit and records the SHA-256 of every file the pipeline may read (03 section 3.3)."
)


class FetchError(RuntimeError):
    pass


def _git(args: list[str], cwd: Path | None = None) -> str:
    try:
        r = subprocess.run(["git", "-c", "advice.detachedHead=false", *args], cwd=cwd, capture_output=True, text=True, check=True)
    except subprocess.CalledProcessError as e:
        raise FetchError(f"git {' '.join(args)} failed: {e.stderr.strip() or e.stdout.strip()}") from e
    return r.stdout.strip()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return "sha256:" + h.hexdigest()


def head_sha(repo_dir: Path) -> str:
    return _git(["rev-parse", "HEAD"], cwd=repo_dir)


def _set_sparse(src: Source, d: Path) -> None:
    flag = "--no-cone" if src.sparse_mode == "no-cone" else "--cone"
    _git(["sparse-checkout", "set", flag, *src.sparse_paths], cwd=d)


def fetch_source(src: Source, cache: Path) -> Path:
    """Clone (blobless, sparse) if needed, then check out the pinned SHA. Idempotent. Returns the clone directory."""
    d = src.dir(cache)
    cache.mkdir(parents=True, exist_ok=True)
    if not (d / ".git").exists():
        _git(["clone", "--filter=blob:none", "--sparse", "--no-checkout", src.url, str(d)])
    _set_sparse(src, d)
    try:
        _git(["cat-file", "-e", f"{src.sha}^{{commit}}"], cwd=d)
    except FetchError:
        _git(["fetch", "--filter=blob:none", "origin", src.sha], cwd=d)
    _git(["checkout", "--force", src.sha], cwd=d)
    got = head_sha(d)
    if got != src.sha:
        raise FetchError(f"{src.id}: checked out {got}, expected {src.sha}")
    return d


def list_score_files(src: Source, cache: Path) -> list[str]:
    """Score files (what later stages parse), repo-relative with forward slashes, sorted."""
    root = src.dir(cache)
    return sorted(p.relative_to(root).as_posix() for p in root.glob(src.score_glob) if p.is_file() and not p.is_symlink())


def licence_evidence_file(src: Source) -> str | None:
    pol = src.licence_policy
    return pol.get("evidence_file") if pol.get("kind") == "repository" else None


def locked_files(src: Source, cache: Path) -> list[str]:
    """Every file whose hash goes in the lock: scores, metadata and the repository licence file."""
    files = set(list_score_files(src, cache))
    root = src.dir(cache)
    for rel in src.metadata_files:
        if (root / rel).is_file():
            files.add(rel)
    ev = licence_evidence_file(src)
    if ev and (root / ev).is_file():
        files.add(ev)
    return sorted(files)


def build_lock_entry(src: Source, cache: Path) -> dict[str, Any]:
    root = src.dir(cache)
    got = head_sha(root)
    if got != src.sha:
        raise FetchError(f"{src.id}: cache is at {got}, sources.yaml pins {src.sha}. Run `fetch` first.")
    entry: dict[str, Any] = {
        "url": src.url,
        "sha": src.sha,
        "files": {rel: sha256_file(root / rel) for rel in locked_files(src, cache)},
    }
    ev = licence_evidence_file(src)
    if ev:
        p = root / ev
        if not p.is_file():
            raise FetchError(f"{src.id}: licence file {ev} is missing")
        entry["licenceEvidence"] = {"file": ev, "sha256": sha256_file(p), "licence": src.licence_policy["licence"]}
    else:
        entry["licenceEvidence"] = {"file": None, "policy": "per-file header", "fields": list(src.licence_policy.get("fields", []))}
    return entry


def load_lock(path: Path = LOCK_YAML) -> dict[str, Any] | None:
    if not path.exists():
        return None
    return load_yaml(path)


def write_lock(sources: list[Source], cache: Path, path: Path = LOCK_YAML, today: str | None = None) -> dict[str, Any]:
    """Hash every locked file and write sources.lock.yaml. `lockedAt` is kept from the previous lock when nothing
    else changed, so a rerun is byte-identical."""
    entries = {}
    for src in sources:
        if not (src.dir(cache) / ".git").exists():
            if src.optional:
                continue
            raise FetchError(f"{src.id}: not fetched. Run `fetch` first.")
        entries[src.id] = build_lock_entry(src, cache)
    prev = load_lock(path)
    locked_at = today or _dt.date.today().isoformat()
    if prev and prev.get("sources") == entries and prev.get("lockedAt"):
        locked_at = str(prev["lockedAt"])
    lock = {"version": LOCK_VERSION, "lockedAt": locked_at, "sources": entries}
    path.write_text(dump_yaml(lock, LOCK_HEADER), encoding="utf-8")
    return lock


def verify_lock(sources: list[Source], cache: Path, lock: dict[str, Any] | None) -> list[str]:
    """Return a list of problems (empty if the cache matches the lock exactly)."""
    if not lock:
        return ["sources.lock.yaml is missing. Run `lock`."]
    problems: list[str] = []
    locked = lock.get("sources", {})
    for src in sources:
        ent = locked.get(src.id)
        root = src.dir(cache)
        if ent is None:
            if not src.optional:
                problems.append(f"{src.id}: not in the lock")
            continue
        if ent["sha"] != src.sha:
            problems.append(f"{src.id}: lock pins {ent['sha']} but sources.yaml pins {src.sha}")
        if not (root / ".git").exists():
            problems.append(f"{src.id}: not fetched")
            continue
        got = head_sha(root)
        if got != ent["sha"]:
            problems.append(f"{src.id}: cache is at {got}, lock pins {ent['sha']}")
        current = {rel: sha256_file(root / rel) for rel in locked_files(src, cache)}
        for rel, h in current.items():
            if rel not in ent["files"]:
                problems.append(f"{src.id}: {rel} is not in the lock")
            elif ent["files"][rel] != h:
                problems.append(f"{src.id}: {rel} hash differs from the lock")
        for rel in ent["files"]:
            if rel not in current:
                problems.append(f"{src.id}: {rel} is in the lock but missing from the cache")
    return problems


def fetch_records(src: Source, cache: Path, lock_entry: dict[str, Any]) -> list[dict[str, Any]]:
    """Stage `fetch` output: one pass record per score file, with the hash recorded in the lock."""
    recs = []
    for rel in list_score_files(src, cache):
        h = lock_entry["files"].get(rel)
        recs.append(
            make_record(
                "fetch", "file", f"{src.id}:{rel}", src.id, "pass" if h else "reject",
                reason=None if h else "file-not-in-lock",
                path=rel, sha256=h or sha256_file(src.dir(cache) / rel), upstream=src.upstream(rel),
            )
        )
    return recs
