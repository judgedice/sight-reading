/** Markdown report of a gate run (docs/accuracy-report.md). */
import { LATENCY_P95_MS, R54_ROOM_LIMIT, type ErrorStats, type GateResult, type InstrumentStats, type Summary } from './aggregate.ts';
import type { SuiteScale } from './jobs.ts';
import { LAUNCH_NAMES, LAUNCH_TIMBRES, type ConditionId } from './types.ts';

export interface ReportMeta {
  scale: SuiteScale;
  scaleName: string;
  durationSec: number;
  workers: number;
  date: string;
  commit: string | null;
  liveProvisionalMs: number;
}

const f = (x: number | null | undefined, d = 3): string => (x === null || x === undefined ? 'n/a' : x.toFixed(d));
const pct = (x: number | null | undefined, d = 1): string => (x === null || x === undefined ? 'n/a' : `${(100 * x).toFixed(d)}%`);

function gateCell(gates: readonly GateResult[], id: string, scope: string, text: string): string {
  const g = gates.find((x) => x.id === id && x.scope === scope);
  if (!g) return text;
  return g.pass ? text : `**${text}** ✗`;
}

const CONDITION_TEXT: Record<ConditionId, string> = {
  clean: 'Clean capture: 48 kHz, no phone mic, room, AGC, noise or click bleed; headphone mode.',
  device:
    '13.2 gate condition ("under click bleed and the phone-mic condition"): phone-mic EQ (150 or 100 Hz 2nd-order high-pass, 7 kHz low-pass), click bleed cycling Tick and Wood at -20 and -10 dB on speakers (template subtraction with a simulated loopback calibration), noise floor -50 or -45 dBFS; no room, no AGC; 48 kHz.',
  planned:
    'Planned room conditions (PLAN R45): each scenario\'s own drawn conditions: room RT60 0.2 to 0.8 s at DRR 3 to 10 dB (70% of takes), phone mic (70%), AGC pumping (30%), capture at 48, 24 or 16 kHz, noise floor, click bleed (Tick or Wood, -20 or -10 dB, 60%).',
};

function instrumentTable(s: Summary, c: ConditionId): string[] {
  const rows = s.perInstrument[c];
  if (!rows) return [];
  const g = s.gates;
  const out = [
    `| Instrument | Takes | Onset F1 (tp/fp/fn) | Onset σ / e90 ms | Verdict agreement (n) | Boundary agr. (n) | False missed | False extras / take | Click extras | Live≠final | Pitch class | Octave err | False red live (n) | c90 c (n) |`,
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const t of LAUNCH_TIMBRES) {
    const x = rows[t] as InstrumentStats | undefined;
    if (!x) continue;
    const sc = `${t} / ${c}`;
    const f1id = c === 'planned' ? 'room-f1' : 'onset-f1';
    out.push(
      [
        LAUNCH_NAMES[t],
        x.takes,
        gateCell(g, f1id, sc, `${f(x.f1, 4)} (${x.tp}/${x.fp}/${x.fn})`),
        `${f(x.onset.sd, 1)} / ${f(x.onset.e90, 1)}`,
        gateCell(g, 'verdict', sc, `${pct(x.verdictAgree)} (${x.verdictN})`),
        `${pct(x.boundaryAgree)} (${x.boundaryN})`,
        gateCell(g, 'false-missed', sc, pct(x.falseMissedRate, 2)),
        gateCell(g, 'false-extras', sc, f(x.falseExtrasPerTake, 2)),
        gateCell(g, 'click-extras', sc, String(x.clickExtras)),
        gateCell(g, 'divergence', sc, pct(x.divergence, 2)),
        gateCell(g, 'pitch-class', sc, pct(x.pitchClassAcc, 2)),
        gateCell(g, 'octave', sc, pct(x.octaveRate, 2)),
        gateCell(g, 'false-red', sc, `${pct(x.falseRedLive, 2)} (${x.falseRedEligible})`),
        gateCell(g, 'c90', sc, `${f(x.c90Steady, 1)} (${x.c90SteadyN})`),
      ].join(' | ').replace(/^/, '| ') + ' |',
    );
  }
  return out;
}

function statsCell(e: ErrorStats | undefined): string {
  return e ? `${e.n} | ${f(e.mean, 2)} | ${f(e.sd, 2)} | ${f(e.rms, 2)} | ${f(e.e90, 2)}` : 'n/a | | | |';
}

export function renderReport(s: Summary, m: ReportMeta): string {
  const L: string[] = [];
  const failing = s.gates.filter((g) => !g.pass);
  const failingNonLimit = failing.filter((g) => !g.note?.includes('R54'));
  L.push('# Synthetic accuracy report (P18)');
  L.push('');
  L.push(`Generated by \`pnpm gates\` (tools/gates/run.ts) on ${m.date}${m.commit ? ` at commit ${m.commit}` : ''}: ${s.takes} synthetic takes, ${m.workers} worker threads, ${(m.durationSec / 60).toFixed(1)} min. Scale \`${m.scaleName}\`: ${m.scale.scenariosPerInstrument} scenarios per launch instrument per condition, ${m.scale.goldenRenders} renders per golden displacement case, ${m.scale.perfectTakes} perfect takes, ${m.scale.tipRuns} injected-error takes per pattern. The machine-readable results are in tools/gates/artifacts/accuracy.json.`);
  L.push('');
  L.push('Every take runs the production analysis path: the P3 synth render with its capture conditions, cut into capture blocks by the production decimator and high-band primitives, then the DSP worker core (DspPipeline with click handling, LiveFollower, final alignment with the voice drift reference) and `gradeWithPatterns`. Ground truth is the render\'s 7.4 onset and pitch on the dry signal; verdict truth applies the same rule functions (`classifyPitch`, `intonationVerdict`, `noteVerdict`) to the true onset and pitch with the resolved tolerances.');
  L.push('');
  L.push(`## Verdict`);
  L.push('');
  L.push(`${s.gates.length} gates, ${s.gates.length - failing.length} pass, ${failing.length} fail${failing.length !== failingNonLimit.length ? ` (${failing.length - failingNonLimit.length} of them are the reverberant-room limit accepted by PLAN R54)` : ''}. Live sharp/flat window: ${m.liveProvisionalMs} ms (config/grading-config.json live.provisionalMs).`);
  L.push('');
  if (failing.length) {
    L.push('Failing gates (thresholds unchanged; these stay failing until the pipeline or the spec changes):');
    L.push('');
    L.push('| Gate | Scope | Metric | Value | Threshold | Source | Note |');
    L.push('| --- | --- | --- | --- | --- | --- | --- |');
    for (const g of failing) L.push(`| ${g.id} | ${g.scope} | ${g.metric} | ${g.value === null ? 'n/a' : f(g.value, 4)} | ${g.op} ${g.threshold} | ${g.source} | ${g.note ?? ''} |`);
    L.push('');
  }

  L.push('## Per-instrument gates (01 §13.2)');
  L.push('');
  L.push('Thresholds: onset F1 ≥ 0.97 at ±30 ms (room: ≥ 0.93, PLAN R45); judgment agreement ≥ 95%; false missed ≤ 1%; false extras ≤ 1 per take; zero click-induced extras; live vs final divergence ≤ 3%; pitch-class accuracy ≥ 99%; octave errors ≤ 0.5%; live sharp/flat on in-tune notes ≤ 1% (PLAN R19); c90 ≤ 5 c on clean capture (01 §8.4: non-vibrato notes with ≥ 250 ms steady, vibrato notes with ≥ 360 ms steady). Bold cells with ✗ fail. The room condition is reported in full but gated only on F1 (R45).');
  L.push('');
  L.push('Definitions. Onset F1: one-to-one greedy matching of detected onsets to the detectable truth onsets at ±30 ms (as the P4c and P4d gates). Verdict agreement: final status, timing verdict and pitch verdict (in tune and not graded count as one) against the truth verdict, over expected notes whose true timing error is more than 15 ms from tRed and the match window and whose true deviation is more than 5 c from redCents (closer than that the detector\'s own error decides; those notes are the "boundary" column). False missed: truly matched notes the final alignment calls missed. False extras: final extras with no played extra or displaced note within 60 ms; click-induced when within 25 ms of a bleed click with no played note within 80 ms. Live≠final: final judgments flagged `rejudged`. False red: notes played in tune (no injected intonation error, |true deviation| ≤ 10 c) that are eligible for a live mark and showed sharp or flat at any time during the take.');
  L.push('');
  for (const c of ['clean', 'device', 'planned'] as ConditionId[]) {
    if (!s.perInstrument[c]) continue;
    L.push(`### ${c === 'clean' ? 'Clean capture' : c === 'device' ? 'Device conditions (click bleed and phone mic)' : 'Planned room conditions'}`);
    L.push('');
    L.push(CONDITION_TEXT[c]);
    L.push('');
    L.push(...instrumentTable(s, c));
    L.push('');
    if (c === 'planned') {
      L.push(`PLAN R54: the R45 room target is a known limit for ${[...R54_ROOM_LIMIT].join(', ')} in strong rooms, and voice is labelled beta outside quiet, dry rooms. Those cells stay marked when they fail.`);
      L.push('');
    }
    const ex = Object.entries(s.perInstrument[c]).flatMap(([t, x]) => x.examples.slice(0, 2).map((e) => `- ${t}: ${e}`));
    if (ex.length) {
      L.push('<details><summary>Sample disagreements</summary>');
      L.push('');
      L.push(...ex);
      L.push('');
      L.push('</details>');
      L.push('');
    }
  }

  L.push('## Onset error by onset profile (σ, e90; artifacts for the floor check)');
  L.push('');
  L.push('Detected 7.4 onset minus the true onset, ms, matched notes. Floor classes: voice (all voice notes), slurred (pitch-change onsets), articulated (silence and dip onsets).');
  L.push('');
  L.push('| Condition | Class | n | mean | σ | rms | e90 |');
  L.push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const [c, byClass] of Object.entries(s.onsetByClass)) for (const k of ['articulated', 'slurred', 'voice']) L.push(`| ${c} | ${k} | ${statsCell(byClass[k])} |`);
  L.push('');
  L.push('Floor check with the measured detector error (01 §8.2: σ_detector = max(measured rms on the device condition, the budget\'s phone detector component); c90 = max(measured, budget)):');
  L.push('');
  L.push('| Class | Measured rms ms | Budget detector σ ms | Used |');
  L.push('| --- | --- | --- | --- |');
  for (const [k, v] of Object.entries(s.measuredSigma)) L.push(`| ${k} | ${f(v.measured, 2)} | ${v.table} | ${f(v.used, 2)} |`);
  L.push('');
  L.push(`Measured c90 (device condition, notes with ≥ 150 ms steady): ${f(s.measuredC90.measured, 2)} c against the budget's ${s.measuredC90.table} c. Floor violations with these values: ${s.floorViolations.length === 0 ? 'none' : s.floorViolations.map((v) => `${v.path} ${v.value} < ${v.floor} (${v.rule})`).join('; ')}.`);
  L.push('');
  L.push('### By onset rule and instrument (PLAN R40: pitch-step crossing bias)');
  L.push('');
  L.push('Mean and e90 per truth onset rule, ms. The pitch-change mean carries the crossing bias accepted by ruling 40 (up to 1.6 ms for a 1-semitone step and 3.6 ms for larger steps on the 1024 window, before segmentation).');
  L.push('');
  L.push('| Condition | Instrument | silence n / mean / e90 | dip n / mean / e90 | pitch-change n / mean / e90 |');
  L.push('| --- | --- | --- | --- | --- |');
  for (const [c, byT] of Object.entries(s.onsetByRule)) {
    for (const t of LAUNCH_TIMBRES) {
      const r = byT[t];
      if (!r) continue;
      const cell = (k: string): string => (r[k] ? `${r[k].n} / ${f(r[k].mean, 2)} / ${f(r[k].e90, 2)}` : '-');
      L.push(`| ${c} | ${LAUNCH_NAMES[t]} | ${cell('silence')} | ${cell('dip')} | ${cell('pitch-change')} |`);
    }
  }
  L.push('');

  L.push('## Latency (01 §12, PLAN R47)');
  L.push('');
  L.push('Sound (true onset) to the first live judgment event for the note, input latency excluded, clean and device takes. Event times are the end of the analysed capture block (256 frames), as in the worker. Sharp/flat marks: sound to the first live sharp or flat on notes with an injected intonation error.');
  L.push('');
  L.push('| Window | n | p50 ms | p95 ms | max ms | Limit |');
  L.push('| --- | --- | --- | --- | --- | --- |');
  for (const [w, v] of Object.entries(s.latency)) {
    const lim = LATENCY_P95_MS[w];
    L.push(`| ${w} | ${v.n} | ${f(v.p50, 1)} | ${gateCell(s.gates, 'latency', `window ${w}`, f(v.p95, 1))} | ${f(v.max, 1)} | p95 ≤ ${lim?.limit} (${lim?.source}) |`);
  }
  L.push('');
  L.push('| Instrument | Sharp/flat marks n | p50 ms | p95 ms |');
  L.push('| --- | --- | --- | --- |');
  for (const [t, v] of Object.entries(s.intonationLatency)) L.push(`| ${LAUNCH_NAMES[t]} | ${v.n} | ${f(v.p50, 0)} | ${f(v.p95, 0)} |`);
  L.push('');
  L.push(`Worker analysis cost per capture block, p95 over takes (wall clock of this run, Node): ${f(s.hopP95Ms, 2)} ms.`);
  L.push('');

  L.push('## Displacement (four golden cases)');
  L.push('');
  L.push('Randomized renders of the golden follow cases (Le Beau, flute, 90 bpm; fresh jitter, cents, held fraction and capture conditions per render; click bleed and phone mic always on). A render passes when the final alignment holds exactly the expected displaced segments (same offset within 0.25 beat, ends within one note), or none for the stop and rejoin cases.');
  L.push('');
  L.push('| Case | Renders | Expected segments | One lost-place status (restart, skip) or none (stop, rejoin) |');
  L.push('| --- | --- | --- | --- |');
  for (const [k, v] of Object.entries(s.displacement)) L.push(`| ${k} | ${v.renders} | ${gateCell(s.gates, 'displacement', k, `${v.pass} (${pct(v.pass / v.renders)})`)} | ${v.lostPlaceOnce} |`);
  const dex = Object.values(s.displacement).flatMap((v) => v.examples);
  if (dex.length) {
    L.push('');
    L.push(...dex.map((x) => `- ${x}`));
  }
  L.push('');

  L.push('## Tip precision (02 §6.2)');
  L.push('');
  L.push(`Perfect takes (shipped corpus, served levels, device condition, timing jitter 3 to 9 ms SD and ±7 c): ${s.perfect.n} takes, ${s.perfect.onlyE30} fire nothing but E30 (E30 fired in ${s.perfect.e30}), ${gateCell(s.gates, 'tips-perfect', `${s.perfect.n} perfect takes`, String(s.perfect.anyNonE30))} fire another pattern${Object.keys(s.perfect.fired).filter((k) => k !== 'E30').length ? `: ${Object.entries(s.perfect.fired).filter(([k]) => k !== 'E30').map(([k, v]) => `${k} ×${v}`).join(', ')}` : ''}.`);
  L.push('');
  L.push('Injected errors (recipes in src/testkit/gates/recipes.ts; shipped corpus, device condition):');
  L.push('');
  L.push('| Pattern | Takes | Fires | Cross-firing (> 0) | Instruments |');
  L.push('| --- | --- | --- | --- | --- |');
  for (const [p, v] of Object.entries(s.tips)) {
    const cross = Object.entries(v.cross).sort((a, b) => b[1] - a[1]).map(([q, n]) => `${q} ${pct(n / Math.max(1, v.n), 0)}`).join(', ');
    const cg = s.gates.find((g) => g.id === 'tips-cross' && g.scope === p);
    L.push(`| ${p} | ${v.n}${v.skipped ? ` (+${v.skipped} without a fitting excerpt)` : ''} | ${gateCell(s.gates, 'tips-hit', p, v.n ? pct(v.hits / v.n, 0) : 'n/a')} | ${cg && !cg.pass ? `**${cross}** ✗` : cross || 'none'} | ${Object.entries(v.timbres).map(([t, n]) => `${t} ${n}`).join(', ')} |`);
  }
  L.push('');

  L.push('## Ghost spelling (PLAN R50)');
  L.push('');
  L.push(`Wrong notes with a final wrong-pitch verdict and a ghost: ${s.ghost.n}; spelled as ruling 50 says (±1 semitone keeps the written letter, beyond it the played pitch's own staff position, sounding the played pitch): ${gateCell(s.gates, 'ghost-spelling', 'all wrong notes with a ghost', `${s.ghost.ok}`)}.${s.ghost.examples.length ? ` Mismatches: ${s.ghost.examples.join('; ')}.` : ''}`);
  L.push('');

  L.push('## Ruling 19 (live sharp/flat window)');
  L.push('');
  const fr = s.gates.filter((g) => g.id === 'false-red-all');
  L.push(`Live sharp/flat marks on in-tune notes over all launch instruments: ${fr.map((g) => `${g.scope.split(' / ')[1]} ${pct(g.value, 2)}`).join(', ')} with the ${m.liveProvisionalMs} ms window. ${fr.every((g) => g.pass) ? 'At or below 1%: the 80 ms window stands.' : 'Above 1%: ruling 19 calls for live.provisionalMs = 150 in config/grading-config.json and a re-run.'}`);
  L.push('');

  if (s.skipped.length) {
    L.push('## Skipped takes');
    L.push('');
    const by = new Map<string, number>();
    for (const x of s.skipped) by.set(x.why, (by.get(x.why) ?? 0) + 1);
    for (const [why, n] of by) L.push(`- ${n} × ${why}`);
    L.push('');
  }

  L.push('## Limits of this report');
  L.push('');
  L.push('- Synthetic audio only (PLAN R3): no real recordings, microphones or rooms. Timbres, rooms and AGC are P3\'s models.');
  L.push('- The 300-scenario set draws from the 24-excerpt fixture corpus (P3); the tip-precision suite draws from the shipped corpus at served levels L3 to L6.');
  L.push('- Latency excludes the input path and is quantized to capture blocks; the browser trace budgets (sound to visible red within 150 ms) are measured by the Playwright suites, not here.');
  L.push('');
  return L.join('\n');
}
