// Bravura metrics for the notation module's measurement table (src/notation/text-metrics.ts).
// Measures every glyph in the table's ranges with canvas measureText in real Chromium. With
// BRAVURA_METRICS_WRITE=1 it rewrites src/notation/bravura-metrics.ts; otherwise it checks the committed table.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { expect, test } from '@playwright/test';
import { BRAVURA_METRICS, BRAVURA_METRICS_EM_PX } from '../../src/notation/bravura-metrics.ts';
import { bravuraDataUrl } from './page.ts';

/** SMuFL ranges VexFlow draws for single-line notation: clefs, time signatures, noteheads, dots, flags,
 * accidentals, articulations, rests, breath marks, dynamics, tuplet digits. */
const RANGES: [number, number][] = [
  [0xe050, 0xe07f],
  [0xe080, 0xe09f],
  [0xe0a0, 0xe0af],
  [0xe1e7, 0xe1e7],
  [0xe240, 0xe25f],
  [0xe260, 0xe26f],
  [0xe4a0, 0xe4bf],
  [0xe4ce, 0xe4ce],
  [0xe4e0, 0xe4ef],
  [0xe520, 0xe53f],
  [0xe880, 0xe88f],
];

const round = (v: number): number => Math.round(v * 100) / 100;
/** Measure at 1000 px: Chromium snaps ink boxes to whole px, so a large size keeps them precise. */
const EM = 1000;

test('Bravura metrics table matches real Chromium measureText', async ({ page }) => {
  const codes = RANGES.flatMap(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => a + i));
  await page.setContent('<!doctype html><html><body></body></html>');
  const measured = await page.evaluate(
    async ({ url, codes, em }) => {
      const face = new FontFace('Bravura', `url(${url})`);
      await face.load();
      (document.fonts as unknown as { add(f: FontFace): void }).add(face);
      const ctx = document.createElement('canvas').getContext('2d')!;
      ctx.font = `${em}px Bravura`;
      const out: Record<string, number[]> = {};
      for (const c of codes) {
        const m = ctx.measureText(String.fromCodePoint(c));
        // Glyphs Bravura lacks fall back to another font; skip them (zero ink or .notdef width).
        if (m.width === 0 && m.actualBoundingBoxAscent === 0 && m.actualBoundingBoxDescent === 0) continue;
        out[c.toString(16)] = [m.width, m.actualBoundingBoxLeft, m.actualBoundingBoxRight, m.actualBoundingBoxAscent, m.actualBoundingBoxDescent];
      }
      return out;
    },
    { url: bravuraDataUrl(), codes, em: EM },
  );
  const table: Record<string, number[]> = {};
  for (const k of Object.keys(measured).sort()) table[k] = measured[k]!.map(round);

  if (process.env['BRAVURA_METRICS_WRITE'] === '1') {
    const lines = Object.entries(table).map(([k, v]) => `  ${k}: [${v.join(', ')}],`);
    const src = [
      '// GENERATED by e2e/notation/bravura-metrics.spec.ts (BRAVURA_METRICS_WRITE=1). Do not edit by hand.',
      '// Bravura (VexFlow 5.2 embedded woff2) canvas measureText in Chromium at 1000 px:',
      '// [advance width, actualBoundingBoxLeft, actualBoundingBoxRight, ascent, descent], keyed by codepoint (hex).',
      `export const BRAVURA_METRICS_EM_PX = ${EM};`,
      'export const BRAVURA_METRICS: Readonly<Record<string, readonly [number, number, number, number, number]>> = {',
      ...lines,
      '};',
      '',
    ].join('\n');
    writeFileSync(join(process.cwd(), 'src/notation/bravura-metrics.ts'), src);
    return;
  }
  const committed = BRAVURA_METRICS as Record<string, readonly number[]>;
  const scale = EM / BRAVURA_METRICS_EM_PX;
  expect(Object.keys(committed).sort()).toEqual(Object.keys(table));
  for (const [k, v] of Object.entries(table)) {
    const c = committed[k]!;
    // 0.1% of an em: far below a pixel at any staff size.
    for (let i = 0; i < 5; i++) expect(Math.abs(c[i]! * scale - v[i]!), `${k}[${i}]`).toBeLessThanOrEqual(1);
  }
});
